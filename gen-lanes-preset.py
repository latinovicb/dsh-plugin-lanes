#!/usr/bin/env python3
"""Generate the `lanes` agent preset from the shipped `standard` preset.

`lanes` is DSH's `standard` preset minus the built-in delegation rows
(`subagent`, `subagent_fork`, `workflow`), so delegation in a lanes session can
only go through the dsh-plugin-subagent-director role lanes: `subagent_role`,
`send_message`, `close_subagent`, `interrupt_agent`, `list_agents`. The
generated preset also mounts this package's `lanes-policy` child row, so the
policy travels with the plugin instead of depending on `AGENTS.md`.

DSH cannot disable nested preset rows from a later patch layer, so the plugin
list has to be copied. This script copies it from the installed DSH and keeps
that copy refreshable:

    ./gen-lanes-preset.py                              # print the block
    ./gen-lanes-preset.py --target cordis.patch.yml

With --target the `- insert:` entry holding `preset-lanes` is replaced in place
(or appended when missing). Re-run it after a DSH upgrade and read the diff:
only changed plugin rows should appear, never a delegation tool coming back.

Sources: `presets/standard.patch.yml` from the installed
`@deepseek-ai/dsh-web-app` (default), or any `dsh --profile <name> --dump-config`
output via --source. Both are the same YAML list shape.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import re
import shutil
import sys

MARKER = "# lanes preset (generated by gen-lanes-preset.py"

# Built-in delegation rows that must not be mounted in a lanes session.
# `tool-subagent-control` (send_message, close_subagent, ...) is kept.
DROP_ALWAYS = ("tool-subagent", "tool-subagent-fork")
DROP_WORKFLOW = ("workflow-ptc", "tool-workflow")
KEEP = "tool-subagent-control"
PRESET_ID = "preset-lanes"
POLICY_PLUGIN = "dsh-plugin-lanes"


def dsh_package() -> pathlib.Path | None:
    dsh = shutil.which("dsh")
    if dsh is None:
        return None
    resolved = pathlib.Path(dsh).resolve()
    for parent in resolved.parents:
        package = parent / "package.json"
        if package.is_file():
            try:
                if json.loads(package.read_text()).get("name") == "@deepseek-ai/dsh":
                    return parent
            except (OSError, ValueError):
                continue
    return None


def default_source() -> pathlib.Path:
    package = dsh_package()
    if package is None:
        sys.exit("cannot locate the installed @deepseek-ai/dsh; pass --source")
    return package / "node_modules/@deepseek-ai/dsh-web-app/presets/standard.patch.yml"


def source_version(source: pathlib.Path) -> str:
    for parent in source.parents:
        package = parent / "package.json"
        if not package.is_file():
            continue
        try:
            data = json.loads(package.read_text())
        except (OSError, ValueError):
            continue
        if data.get("name") == "@deepseek-ai/dsh":
            return f"DSH {data.get('version', '?')}"
    return "the installed DSH"


def indent_of(line: str) -> int:
    return len(line) - len(line.lstrip(" "))


def top_level_blocks(lines: list[str]) -> list[tuple[int, int]]:
    """Split a YAML entry list into [start, end) spans of its `- ` blocks."""
    starts = [index for index, line in enumerate(lines) if line.startswith("- ")]
    return [(start, starts[at + 1] if at + 1 < len(starts) else len(lines)) for at, start in enumerate(starts)]


def standard_plugins(lines: list[str]) -> tuple[list[str], int]:
    """Return the `plugins:` rows of `preset-standard` and their indentation."""
    for at, line in enumerate(lines):
        if re.match(r"^\s*- id: preset-standard\s*$", line):
            base = indent_of(line)
            end = len(lines)
            for index in range(at + 1, len(lines)):
                if re.match(r"^\s*-\s", lines[index]) and indent_of(lines[index]) <= base:
                    end = index
                    break
            body = lines[at:end]
            for offset, row in enumerate(body):
                if row.strip() == "plugins:":
                    rows = body[offset + 1 :]
                    current = min(indent_of(row) for row in rows if row.strip())
                    return rows, current
            break
    raise SystemExit("source has no `preset-standard` entry with a plugins: list")


def drop_rows(rows: list[str], ids: tuple[str, ...]) -> tuple[list[str], list[str]]:
    """Delete whole `- id: <id>` entries; return (kept rows, dropped ids)."""
    wanted = set(ids)
    kept: list[str] = []
    dropped: list[str] = []
    index = 0
    while index < len(rows):
        match = re.match(r"^(\s*)- id: (\S+)\s*$", rows[index])
        if match is None or match.group(2) not in wanted:
            kept.append(rows[index])
            index += 1
            continue
        dropped.append(match.group(2))
        base = len(match.group(1))
        index += 1
        while index < len(rows):
            line = rows[index]
            if line.strip() and indent_of(line) <= base:
                break
            index += 1
    return kept, dropped


def reindent(rows: list[str], current: int, target: int) -> list[str]:
    shift = target - current
    if shift == 0:
        return rows
    if shift > 0:
        return [line if not line.strip() else " " * shift + line for line in rows]
    return [line if not line.strip() else line[-shift:] for line in rows]


def render(source: pathlib.Path, keep_workflow: bool) -> str:
    rows, current = standard_plugins(source.read_text().splitlines())
    ids = DROP_ALWAYS if keep_workflow else DROP_ALWAYS + DROP_WORKFLOW
    kept, dropped = drop_rows(rows, ids)
    for wanted in ids:
        if wanted not in dropped:
            raise SystemExit(f"source has no `- id: {wanted}` row; refusing a stale copy")
    if len(dropped) != len(ids) or not any(re.match(rf"^\s*- id: {KEEP}\s*$", row) for row in kept):
        raise SystemExit(f"removal sanity check failed (dropped {dropped}); refusing")

    why = ", ".join(f"`{row}`" for row in dropped)
    block = [
        f"{MARKER} from {source_version(source)})",
        f"# `standard` minus {why}; delegation goes only through role lanes.",
        "# Do not edit: refresh with `./gen-lanes-preset.py --target cordis.patch.yml`",
        "- insert:",
        f"    - id: {PRESET_ID}",
        "      name: '@deepseek-ai/dsh-agent-preset'",
        "      config:",
        "        id: lanes",
        "        name: lanes",
        "        description: standard minus the built-in delegation tools; role lanes only",
        "        order: 0",
        "        plugins:",
        *reindent(kept, current, 10),
        "          - id: lanes-policy",
        f"            name: {POLICY_PLUGIN}",
    ]
    return "\n".join(block) + "\n"


def update_target(target: pathlib.Path, block: str) -> None:
    lines = target.read_text().splitlines()
    for start, end in top_level_blocks(lines):
        body = lines[start:end]
        if not any(re.match(rf"^\s*- id: {PRESET_ID}\s*$", row) for row in body):
            continue
        if body[0].strip() != "- insert:":
            raise SystemExit(f"{target}: `{PRESET_ID}` sits outside an `- insert:` entry; fix it by hand")
        if sum(1 for row in body if re.match(r"^    - id: ", row)) != 1:
            raise SystemExit(f"{target}: the insert entry holding `{PRESET_ID}` has other items; split it first")
        while start > 0 and lines[start - 1].lstrip().startswith("#"):
            start -= 1
        if MARKER not in "\n".join(lines[start:end]):
            raise SystemExit(f"{target}: `{PRESET_ID}` has hand-written comments above it; regenerate by hand")
        updated = [*lines[:start], *block.splitlines(), *lines[end:]]
        target.write_text("\n".join(updated) + "\n")
        return
    text = target.read_text()
    target.write_text(text + ("\n" if not text.endswith("\n") else "") + block)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", type=pathlib.Path, default=None, help="standard.patch.yml or a --dump-config dump")
    parser.add_argument("--target", type=pathlib.Path, default=None, help="patch file to update in place")
    parser.add_argument("--keep-workflow", action="store_true", help="keep workflow-ptc and tool-workflow")
    args = parser.parse_args()

    source = args.source or default_source()
    if not source.is_file():
        raise SystemExit(f"no such source: {source}")
    block = render(source, args.keep_workflow)
    if args.target is None:
        sys.stdout.write(block)
        return
    update_target(args.target, block)
    print(f"updated {args.target} from {source}")


if __name__ == "__main__":
    main()
